// Fusion dans le réservoir affiché par la bulle de Rex (js/37-citations-rex.js).
// Les doublons de texte sont écartés : plusieurs sentences reviennent d'une famille à l'autre.
const REX_RESERVOIRS = [REX_CITATIONS_PHILO, REX_CIT_GRECE, REX_CIT_ROME, REX_CIT_PERSE, REX_CIT_ROIS, REX_CIT_CHRETIEN, REX_CIT_AQUIN];

(function rexFusionnerReservoir() {
  if (typeof REX_CITATIONS === 'undefined') return;
  const cle = v => String(v || '').toLowerCase().normalize('NFD').replace(/[^a-z0-9]/g, '');
  const vues = new Set(REX_CITATIONS.map(c => cle(c.t)));
  for (const famille of REX_RESERVOIRS) {
    for (const c of famille) {
      const k = cle(c.t);
      if (!vues.has(k)) { REX_CITATIONS.push(c); vues.add(k); }
    }
  }
})();
